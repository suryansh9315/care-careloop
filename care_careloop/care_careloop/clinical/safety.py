"""Deterministic safety screen run against the drafted regimen.

Ported from `legacy/src/orchestration/safety.ts`.

Allergy matches are ``critical`` and gate clinician approval. Duplicates and
interactions are warnings -- real, but a clinician's call. Nothing here is
generated by a model.
"""

from __future__ import annotations

import re
from typing import Iterable, NamedTuple, Protocol

from .models import (
    ConditionModule,
    MedicationSummary,
    MedOrder,
    RiskAnswer,
    RiskFinding,
    SafetyFinding,
    ScoreResult,
)


class _Interaction(NamedTuple):
    a: str
    b: str
    message: str


#: Small, explicit interaction table. Extending it is a clinical review task.
INTERACTIONS: tuple[_Interaction, ...] = (
    _Interaction(
        "sertraline",
        "tramadol",
        "SSRI with tramadol increases serotonin syndrome and seizure risk.",
    ),
    _Interaction(
        "sertraline",
        "warfarin",
        "SSRIs increase bleeding risk with warfarin; INR monitoring is needed.",
    ),
    _Interaction(
        "sertraline",
        "linezolid",
        "Contraindicated combination — serotonin syndrome risk.",
    ),
    _Interaction(
        "formoterol",
        "propranolol",
        "Non-selective beta blockers antagonise beta-agonist bronchodilation.",
    ),
    _Interaction(
        "prednisone",
        "ibuprofen",
        "Corticosteroid with an NSAID increases gastrointestinal bleeding risk.",
    ),
)

_NON_ALNUM = re.compile(r"[^a-z0-9 ]")
_WHITESPACE = re.compile(r"\s+")


class _Codeable(Protocol):
    display: str
    ingredients: list[str] | None


def _normalise(value: str) -> str:
    return _WHITESPACE.sub(" ", _NON_ALNUM.sub(" ", value.lower())).strip()


def _tokens_for(item: _Codeable) -> list[str]:
    """Ingredient tokens if declared, else the long words of the display name.

    The ``len > 3`` filter on display words is what stops "mg", "oral" and "80"
    from matching everything.
    """
    if item.ingredients:
        return [_normalise(i) for i in item.ingredients]
    return [t for t in _normalise(item.display).split(" ") if len(t) > 3]


def _allergy_matches(allergy: str, med: MedOrder) -> bool:
    allergy_token = _normalise(allergy)
    if not allergy_token:
        return False
    return any(
        token == allergy_token
        or allergy_token in token
        or token in allergy_token
        for token in _tokens_for(med)
    )


def _duplicate_match(current: MedicationSummary, med: MedOrder) -> str | None:
    current_tokens = set(_tokens_for(current))
    for token in _tokens_for(med):
        if token in current_tokens:
            return token
    return None


def _dedupe(findings: Iterable[SafetyFinding]) -> list[SafetyFinding]:
    seen: set[str] = set()
    out: list[SafetyFinding] = []
    for finding in findings:
        key = f"{finding.code}|{finding.medication or ''}|{finding.message}"
        if key in seen:
            continue
        seen.add(key)
        out.append(finding)
    return out


def check_regimen_safety(
    regimen: list[MedOrder],
    allergies: list[str],
    current_medications: list[MedicationSummary],
) -> list[SafetyFinding]:
    """Screen a drafted regimen against the patient's recorded chart.

    Finding order is load-bearing: dedupe keeps the first occurrence, so the
    nesting below (per medication: allergies, then per active medication a
    duplicate check followed by the interaction table) is part of the frozen
    behaviour, not an implementation detail.
    """
    findings: list[SafetyFinding] = []

    for med in regimen:
        for allergy in allergies:
            if _allergy_matches(allergy, med):
                findings.append(
                    SafetyFinding(
                        severity="critical",
                        code="allergy-match",
                        medication=med.display,
                        message=(
                            f'Recorded allergy to "{allergy}" matches {med.display}. '
                            "A clinician must acknowledge this before the plan can be approved."
                        ),
                    )
                )

        for current in current_medications:
            shared = _duplicate_match(current, med)
            if shared:
                findings.append(
                    SafetyFinding(
                        severity="warning",
                        code="duplicate-therapy",
                        medication=med.display,
                        message=(
                            f'{med.display} overlaps with the active medication '
                            f'"{current.display}" (shared ingredient: {shared}). '
                            "Confirm whether this is a replacement or an addition."
                        ),
                    )
                )

            med_tokens = _tokens_for(med)
            current_tokens = _tokens_for(current)
            for rule in INTERACTIONS:
                hit = (rule.a in med_tokens and rule.b in current_tokens) or (
                    rule.b in med_tokens and rule.a in current_tokens
                )
                if hit:
                    findings.append(
                        SafetyFinding(
                            severity="warning",
                            code="interaction",
                            medication=med.display,
                            message=f'{med.display} with "{current.display}": {rule.message}',
                        )
                    )

    if not regimen:
        findings.append(
            SafetyFinding(
                severity="info",
                code="note",
                message="This protocol step drafts no medication. Review is still required.",
            )
        )

    return _dedupe(findings)


def evaluate_risk(
    module: ConditionModule, risk_answers: list[RiskAnswer], score: ScoreResult
) -> list[RiskFinding]:
    """Run the module's risk rules, degrading to a warning if they fail.

    A broken rule must not lose the call: the answers are still on the record
    and a clinician is told to read them.
    """
    if module.risk_rules is None:
        return []
    try:
        return module.risk_rules(risk_answers, score)
    except Exception:  # noqa: BLE001 - a rule bug must not drop the call
        return [
            RiskFinding(
                severity="warning",
                code="risk-rules-failed",
                message=(
                    "Risk rules could not be evaluated for this call. "
                    "Review the raw answers manually."
                ),
            )
        ]


def has_critical(findings: Iterable[SafetyFinding | RiskFinding]) -> bool:
    return any(f.severity == "critical" for f in findings)


def should_escalate(
    *,
    urgent_step: bool,
    safety: list[SafetyFinding],
    risks: list[RiskFinding],
) -> bool:
    """A critical risk finding forces escalation even when the band would not.

    For example a prior asthma ICU admission with a mid-range ACT.
    """
    return urgent_step or has_critical(safety) or has_critical(risks)
